/* No dependency needed: node tests/table-import.cjs */
const assert=require('node:assert/strict');
const {parse,layout}=require('../assets/diagram-table.js');
const rows=parse('項目\t内容\t備考\n産地\tエチオピア\t花の香り\n焙煎\t浅煎り\t酸味');
assert.equal(rows.length,3);
assert.deepEqual(rows[0],['項目','内容','備考']);
const obj=layout(rows,{style:'table',canvas:'auto'});
assert.equal(obj.schema,'kps-diagram-v1');
assert.equal(obj.elements.length,9);
assert.equal(obj.elements[0].fill,'#e5d5c5');
assert.equal(obj.elements[3].fill,'#f3e7da');
assert.equal(obj.elements[4].weight,'normal');
assert.ok(obj.width>=320&&obj.width<=4096);
assert.ok(obj.height>=200&&obj.height<=4096);
assert.ok(obj.elements.every(e=>e.x>=0&&e.y>=0&&e.x+e.w<=obj.width&&e.y+e.h<=obj.height));
const note=layout(rows,{style:'diagram',canvas:'note',headerCol:false});
assert.equal(note.width,1100);
assert.equal(note.elements.length,9);
assert.equal(note.elements[3].weight,'normal');
assert.equal(note.elements[0].radius,22);
assert.ok(note.elements.every(e=>e.x+e.w<=1100));
assert.deepEqual(parse('| 項目 | 内容 |\n| :--- | ---: |\n| A | 100 |'),[['項目','内容'],['A','100']]);
assert.deepEqual(parse('項目\t内容\n"A\tB"\t"1\n2"'),[['項目','内容'],['A\tB','1\n2']]);
assert.deepEqual(parse('頭\t本文\n一\t短い\n二'),[['頭','本文'],['一','短い'],['二','']]);
assert.throws(()=>parse('文字 文字\n文字 文字'),/タブ区切り/);
assert.throws(()=>parse('a\tb\n"broken\tc'),/引用符/);
const tooLarge=Array.from({length:11},()=>Array(10).fill('x').join('\t')).join('\n');
assert.throws(()=>parse(tooLarge),/最大100セル/);
console.log('KPS table importer unit tests OK');
